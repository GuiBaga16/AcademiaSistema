    private void carregaInformacoes() {
        ArrayList<Exercicio> exercicios = ExerciciosController.recuperaTodos();

        if (exercicios == null) {
            Mensagem.erro("Ocorreu um erro ao consultar os exercicios.");
        } else {
            tblExercicio.setModel(new AbstractTableModel() {

                @Override
                public String getColumnName(int column) {
                    switch (column) {
                        case 0:
                            return "Id";
                        case 1:
                            return "Nome";
                        case 2:
                            return "EquipamentoId";
                        case 3:
                            return "Descricao";
                        default:
                            return "";
                    }
                }

                @Override
                public int getColumnCount() {
                    return 4;
                }

                @Override
                public int getRowCount() {
                    return exercicios.size();
                }

                @Override
                public Object getValueAt(int rowIndex, int columnIndex) {
                    Exercicio e = exercicios.get(rowIndex);

                    if (e != null) {
                        switch (columnIndex) {
                            case 0:
                                return e.getId();
                            case 1:
                                return e.getNome();
                            case 2:
                                return e.getEquipamentoId();
                            case 3:
                                return e.getDescricao();
                        }
                    }

                    return "n/d";
                }
            });
        }
    }

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        int linha = tblExercicio.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um exercício para editar.");
            return;
        }

        int id = Integer.parseInt(String.valueOf(tblExercicio.getModel().getValueAt(linha, 0)));

        Exercicio exercicio = ExerciciosController.recuperaUm(id);

        if (exercicio == null) {
            Mensagem.erro("Exercício não encontrado.");
        } else {
            idExercicioEditando = exercicio.getId();

            txtNome.setText(exercicio.getNome());
            txtDescricao.setText(exercicio.getDescricao());

            for (int i = 0; i < listaEquipamentos.size(); i++) {
                if (listaEquipamentos.get(i).getId() == exercicio.getEquipamentoId()) {
                    cbxEquipamento.setSelectedIndex(i);
                    break;
                }
            }
        }
        jtpExercicio.setSelectedIndex(1);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        int linha = tblExercicio.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um exercício para excluir.");
            return;
        }

        int Id = Integer.parseInt(String.valueOf(tblExercicio.getModel().getValueAt(linha, 0)));

        Exercicio exercicio = ExerciciosController.recuperaUm(Id);

        if (exercicio == null) {
            Mensagem.erro("Exercício não encontrado.");
        } else {
            boolean retorno = ExerciciosController.excluir(exercicio.getId());

            if (retorno) {
                Mensagem.informacao("Exercício " + Id + " apagado com sucesso!");
                carregaInformacoes();
            } else {
                Mensagem.erro(
                        "Ocorreu um erro ao tentar excluir o exercício " + Id
                );
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

