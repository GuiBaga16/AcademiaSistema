    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText();
        String descricao = txtDescricao.getText();
        int indice = cbxEquipamento.getSelectedIndex();

        if (indice < 0 || indice >= listaEquipamentos.size()) {
            Mensagem.erro("Selecione um equipamento.");
            return;
        }

        int equipamentoId = listaEquipamentos.get(indice).getId();

        if (idExercicioEditando == 0) {

            Exercicio novoExercicio = new Exercicio(nome, descricao, equipamentoId);
            boolean retorno = ExerciciosController.salvar(novoExercicio);

            if (retorno) {
                Mensagem.informacao("Exercicio cadastrado com sucesso!");
                txtNome.setText("");
                cbxEquipamento.setSelectedIndex(-1);
                txtDescricao.setText("");
                carregaInformacoes();

            } else {
                Mensagem.erro("Ocorreu um erro ao cadastrar o exercicio.");
            }

        } else {

            Exercicio editarExercicio = new Exercicio(idExercicioEditando, nome, descricao, equipamentoId);

            boolean retorno = ExerciciosController.editar(editarExercicio);

            if (retorno) {
                Mensagem.informacao("Exercicio " + idExercicioEditando + " editado com sucesso!");
                txtNome.setText("");
                cbxEquipamento.setSelectedIndex(-1);
                txtDescricao.setText("");

                idExercicioEditando = 0;
                carregaInformacoes();

            } else {
                Mensagem.erro("Ocorreu um erro ao editar o exercicio.");
            }
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void carregaEquipamentos() {
        listaEquipamentos = Controllers.EquipamentosController.recuperaTodos();

        cbxEquipamento.removeAllItems();

        for (Equipamento equipamento : listaEquipamentos) {
            cbxEquipamento.addItem(equipamento.getNome());
        }

        cbxEquipamento.setSelectedIndex(-1);
    }


