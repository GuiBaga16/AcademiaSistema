    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText().trim();
        String descricao = txtDescricao.getText().trim();
        int indice = cbxTreino.getSelectedIndex();

        if (nome.isEmpty()) {
            Mensagem.erro("Informe o nome do treino.");
            return;
        }

        if (indice < 0 || indice >= listaTiposTreino.size()) {
            Mensagem.erro("Selecione um tipo de treino.");
            return;
        }

        int tipoTreinoId = listaTiposTreino.get(indice).getId();
        boolean retorno;

        if (idTreinoEditando == 0) {
            Treino novoTreino = new Treino(nome, descricao, tipoTreinoId);

            retorno = TreinosController.salvar(novoTreino);

            if (retorno) {
                Mensagem.informacao("Treino cadastrado com sucesso!");
                txtNome.setText("");
                cbxTreino.setSelectedIndex(-1);
                txtDescricao.setText("");
                carregaInformacoes();
            } else {
                Mensagem.erro("Erro ao cadastrar o treino.");
                return;
            }

        } else {
            Treino treinoEditado = new Treino(idTreinoEditando, nome, descricao, tipoTreinoId);

            retorno = TreinosController.editar(treinoEditado);

            if (retorno) {
                Mensagem.informacao("Treino " + idTreinoEditando + " editado com sucesso!");
                txtNome.setText("");
                cbxTreino.setSelectedIndex(-1);
                txtDescricao.setText("");
            } else {
                Mensagem.erro("Erro ao editar o treino.");
                return;
            }
        }

        carregaInformacoes();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void carregaTiposTreino() {
        listaTiposTreino = TiposTreinoController.recuperaTodos();

        cbxTreino.removeAllItems();

        for (TipoTreino tipo : listaTiposTreino) {
            cbxTreino.addItem(tipo.getNome());
        }

        cbxTreino.setSelectedIndex(-1);
    }

