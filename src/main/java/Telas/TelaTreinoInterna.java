    private void carregaInformacoes() {
        ArrayList<Treino> treinos = TreinosController.recuperaTodos();

        tblExercicio.setModel(new AbstractTableModel() {

            @Override
            public String getColumnName(int column) {
                switch (column) {
                    case 0:
                        return "Id";
                    case 1:
                        return "Nome";
                    case 2:
                        return "Tipo de treino";
                    case 3:
                        return "Descrição";
                    default:
                        return "";
                }
            }

            @Override
            public int getColumnCount() {
                return 4;
            }

            @Override
            public int getRowCount() {
                return treinos.size();
            }

            @Override
            public Object getValueAt(int rowIndex, int columnIndex) {
                Treino treino = treinos.get(rowIndex);

                switch (columnIndex) {
                    case 0:
                        return treino.getId();
                    case 1:
                        return treino.getNome();
                    case 2:
                        return treino.getTipoTreinoId();
                    case 3:
                        return treino.getDescricao();
                    default:
                        return "";
                }
            }
        });
    }


    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        int linha = tblExercicio.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um treino para editar.");
            return;
        }

        int id = Integer.parseInt(String.valueOf(tblExercicio.getModel().getValueAt(linha, 0)));

        Treino treino = TreinosController.recuperaUm(id);

        if (treino == null) {
            Mensagem.erro("Treino não encontrado.");
            return;
        } else {
            idTreinoEditando = treino.getId();

            txtNome.setText(treino.getNome());
            txtDescricao.setText(treino.getDescricao());

            cbxTreino.setSelectedIndex(-1);

            for (int i = 0; i < listaTiposTreino.size(); i++) {
                if (listaTiposTreino.get(i).getId() == treino.getTipoTreinoId()) {
                    cbxTreino.setSelectedIndex(i);
                    break;
                }
            }
        }
        jtpExercicio.setSelectedIndex(1);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblExercicio.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um treino para excluir.");
            return;
        }

        int id = Integer.parseInt(String.valueOf(tblExercicio.getModel().getValueAt(linha, 0)));

        Treino treino = TreinosController.recuperaUm(id);

        if (treino == null) {
            Mensagem.erro("Treino não encontrado.");
            return;
        }

        boolean retorno = TreinosController.excluir(treino.getId());

        if (retorno) {
            Mensagem.informacao("Treino " + id + " excluído com sucesso!");
            carregaInformacoes();
        } else {
            Mensagem.erro(
                    "Não foi possível excluir o treino. "
                    + "Verifique se ele está associado a alunos ou exercícios."
            );
        }

    }//GEN-LAST:event_btnExcluirActionPerformed

