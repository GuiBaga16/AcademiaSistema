    private void carregaInformacoes() {
        ArrayList<Aluno> alunos = AlunosController.recuperaTodos();

        if (alunos == null) {
            Mensagem.erro("Ocorreu um erro ao consultar os alunos.");
        } else {
            tblAluno.setModel(new AbstractTableModel() {

                @Override
                public String getColumnName(int column) {
                    switch (column) {
                        case 0:
                            return "Id";
                        case 1:
                            return "Nome";
                        case 2:
                            return "Documento";
                        case 3:
                            return "E-mail";
                        case 4:
                            return "Telefone";
                        case 5:
                            return "Data de Nascimento";
                        default:
                            return "";
                    }
                }

                @Override
                public int getColumnCount() {
                    return 6;
                }

                @Override
                public int getRowCount() {
                    return alunos.size();
                }

                @Override
                public Object getValueAt(int rowIndex, int columnIndex) {
                    Aluno a = alunos.get(rowIndex);

                    if (a != null) {
                        switch (columnIndex) {
                            case 0:
                                return a.getId();
                            case 1:
                                return a.getNome();
                            case 2:
                                return a.getDocumento();
                            case 3:
                                return a.getEmail();
                            case 4:
                                return a.getTelefone();
                            case 5:
                                return a.getDataNascimento();
                        }
                    }

                    return "n/d";
                }
            });
        }
    }

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblAluno.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um aluno para excluir.");
            return;
        }
        int Id = Integer.parseInt(String.valueOf(tblAluno.getModel().getValueAt(linha, 0)));

        Aluno aluno = AlunosController.recuperaUm(Id);
        if (aluno == null) {
            Mensagem.erro("Aluno não encontrado.");
        } else {
            boolean retorno = AlunosController.excluir(aluno.getId());

            if (retorno) {
                Mensagem.informacao("Aluno " + Id + " apagado com sucesso!");
                carregaInformacoes();
            } else {
                Mensagem.erro("Ocorreu um erro ao tentar excluir o aluno " + Id);
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linha = tblAluno.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um aluno para editar.");
            return;
        }

        int Id = Integer.parseInt(String.valueOf(tblAluno.getModel().getValueAt(linha, 0)));

        Aluno aluno = AlunosController.recuperaUm(Id);
        if (aluno == null) {
            Mensagem.erro("Aluno não encontrado.");    
        } else {
            idAlunoEditando = aluno.getId();
            txtNome.setText(aluno.getNome());
            txtDocumento.setText(aluno.getDocumento());
            txtEmail.setText(aluno.getEmail());
            txtTelefone.setText(aluno.getTelefone());

            if (aluno.getDataNascimento() != null) {
                txtDataNascimento.setText(aluno.getDataNascimento().toString());
            } else {
                txtDataNascimento.setText("");
            }

            jtpAluno.setSelectedIndex(1);
            txtNome.requestFocus();
        }
    }//GEN-LAST:event_btnEditarActionPerformed

