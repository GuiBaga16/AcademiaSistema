    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText();
        String documento = txtDocumento.getText();
        String email = txtEmail.getText();
        String telefone = txtTelefone.getText();

        java.time.LocalDate dataNascimento = null;

        if (!txtDataNascimento.getText().trim().isEmpty()) {
            try {
                dataNascimento = java.time.LocalDate.parse(
                        txtDataNascimento.getText().trim()
                );
            } catch (java.time.format.DateTimeParseException ex) {
                Mensagem.erro("Data de nascimento inválida. Use o formato AAAA-MM-DD.");
                return;
            }
        }

        if (idAlunoEditando == 0) {

            Aluno novoAluno = new Aluno(nome, documento, email, telefone, dataNascimento);
            boolean retorno = AlunosController.salvar(novoAluno);

            if (retorno) {
                Mensagem.informacao("Aluno cadastrado com sucesso!");
                txtNome.setText("");
                txtDocumento.setText("");
                txtEmail.setText("");
                txtTelefone.setText("");
                txtDataNascimento.setText("");
                carregaInformacoes();

            } else {
                Mensagem.erro("Ocorreu um erro ao cadastrar o aluno.");
            }
        } else {

            Aluno editarAluno = new Aluno(idAlunoEditando, nome, documento, email, telefone, dataNascimento);

            boolean retorno = AlunosController.editar(editarAluno);

            if (retorno) {
                Mensagem.informacao("Aluno " + idAlunoEditando + " editado com sucesso!");
                txtNome.setText("");
                txtDocumento.setText("");
                txtEmail.setText("");
                txtTelefone.setText("");
                txtDataNascimento.setText("");

                idAlunoEditando = 0;
                carregaInformacoes();

            } else {
                Mensagem.erro("Ocorreu um erro ao editar o aluno.");
            }
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

