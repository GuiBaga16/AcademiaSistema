    private void btnAssociarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAssociarActionPerformed
        int indiceAluno = cbxEquipamento2.getSelectedIndex();
        int indiceTreino = cbxEquipamento1.getSelectedIndex();

        if (indiceAluno < 0 || indiceAluno >= listaAlunos.size()) {
            Mensagem.erro("Selecione um aluno.");
            return;
        }

        if (indiceTreino < 0 || indiceTreino >= listaTreinos.size()) {
            Mensagem.erro("Selecione um treino.");
            return;
        }

        int alunoId = listaAlunos.get(indiceAluno).getId();
        int treinoId = listaTreinos.get(indiceTreino).getId();

        boolean retorno = AlunoTreinoController.salvar(alunoId, treinoId);

        if (retorno) {
            Mensagem.informacao("Aluno associado ao treino com sucesso!");

            cbxEquipamento2.setSelectedIndex(-1);
            cbxEquipamento1.setSelectedIndex(-1);
            carregaInformacoes();

        } else {
            Mensagem.erro(
                    "Não foi possível associar o aluno ao treino. "
                    + "Verifique se essa associação já existe."
            );
        }
    }//GEN-LAST:event_btnAssociarActionPerformed

