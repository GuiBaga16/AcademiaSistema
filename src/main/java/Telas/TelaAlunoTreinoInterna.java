    private void carregaAlunos() {
        listaAlunos = AlunosController.recuperaTodos();

        cbxEquipamento2.removeAllItems();

        for (Aluno aluno : listaAlunos) {
            cbxEquipamento2.addItem(aluno.getNome());
        }

        cbxEquipamento2.setSelectedIndex(-1);
    }

    private void carregaTreinos() {
        listaTreinos = TreinosController.recuperaTodos();

        cbxEquipamento1.removeAllItems();

        for (Treino treino : listaTreinos) {
            cbxEquipamento1.addItem(treino.getNome());
        }

        cbxEquipamento1.setSelectedIndex(-1);
    }

    private void carregaInformacoes() {
        ArrayList<AlunoTreino> associacoes = AlunoTreinoController.recuperaTodos();

        if (associacoes == null) {
            Mensagem.erro("Ocorreu um erro ao consultar as associações.");
            return;
        }

        tblAlunoExercicio.setModel(new AbstractTableModel() {

            @Override
            public String getColumnName(int column) {
                switch (column) {
                    case 0:
                        return "Aluno ID";
                    case 1:
                        return "Aluno";
                    case 2:
                        return "Treino ID";
                    case 3:
                        return "Treino";
                    default:
                        return "";
                }
            }

            @Override
            public int getColumnCount() {
                return 4;
            }

            @Override
            public int getRowCount() {
                return associacoes.size();
            }

            @Override
            public Object getValueAt(int rowIndex, int columnIndex) {
                AlunoTreino associacao = associacoes.get(rowIndex);

                switch (columnIndex) {
                    case 0:
                        return associacao.getAlunoId();
                    case 1:
                        return associacao.getAlunoNome();
                    case 2:
                        return associacao.getTreinoId();
                    case 3:
                        return associacao.getTreinoNome();
                    default:
                        return "n/d";
                }
            }
        });
    }

