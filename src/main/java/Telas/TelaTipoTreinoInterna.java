    private void carregaInformacoes() {
        ArrayList<TipoTreino> tipos = TiposTreinoController.recuperaTodos();

        tblTipoTreino.setModel(new AbstractTableModel() {

            private final String[] colunas = {
                "ID", "Nome", "Descrição"
            };

            @Override
            public String getColumnName(int coluna) {
                return colunas[coluna];
            }

            @Override
            public int getRowCount() {
                return tipos.size();
            }

            @Override
            public int getColumnCount() {
                return colunas.length;
            }

            @Override
            public Object getValueAt(int linha, int coluna) {
                TipoTreino tipo = tipos.get(linha);

                switch (coluna) {
                    case 0:
                        return tipo.getId();
                    case 1:
                        return tipo.getNome();
                    case 2:
                        return tipo.getDescricao();
                    default:
                        return null;
                }
            }
        });
    }

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linha = tblTipoTreino.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um tipo de treino para editar.");
            return;
        }

        int id = Integer.parseInt(String.valueOf(tblTipoTreino.getValueAt(linha, 0)));

        TipoTreino tipo = TiposTreinoController.recuperaUm(id);

        if (tipo == null) {
            Mensagem.erro("Tipo de treino não encontrado.");
            return;
        }

        idTipoTreinoEditando = tipo.getId();
        txtNome.setText(tipo.getNome());
        txtDescricao.setText(tipo.getDescricao());

        jtpExercicio.setSelectedIndex(1);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblTipoTreino.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um tipo de treino para excluir.");
            return;
        }

        int id = Integer.parseInt(String.valueOf(tblTipoTreino.getValueAt(linha, 0)));

        boolean retorno = TiposTreinoController.excluir(id);

        if (retorno) {
            Mensagem.informacao("Tipo de treino excluído com sucesso!");
            carregaInformacoes();
        } else {
            Mensagem.erro(
                    "Não foi possível excluir. Verifique se esse tipo "
                    + "está sendo utilizado por algum treino.");
        }

    }//GEN-LAST:event_btnExcluirActionPerformed

