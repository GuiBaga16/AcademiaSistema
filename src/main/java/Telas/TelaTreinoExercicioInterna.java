    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        int indiceTreino = cbxTreino.getSelectedIndex();
        int indiceExercicio = cbxExercicio.getSelectedIndex();

        if (indiceTreino < 0 || indiceTreino >= listaTreinos.size()) {
            Mensagem.erro("Selecione um treino.");
            return;
        }

        ArrayList<Exercicio> listaExercicios = ExerciciosController.recuperaTodos();

        if (indiceExercicio < 0 || indiceExercicio >= listaExercicios.size()) {
            Mensagem.erro("Selecione um exercício.");
            return;
        }

        int series;
        int repeticoes;
        double carga;

        try {
            series = Integer.parseInt(txtSeries.getText().trim());
            repeticoes = Integer.parseInt(txtRepeticoes.getText().trim());
            carga = Double.parseDouble(
                    txtCarga.getText().trim().replace(",", ".")
            );

            if (series <= 0 || repeticoes <= 0 || carga < 0) {
                Mensagem.erro(
                        "Séries e repetições devem ser positivas, "
                        + "e a carga não pode ser negativa.");
                return;
            }
        } catch (NumberFormatException ex) {
            Mensagem.erro("Informe séries, repetições e carga válidas.");
            return;
        }

        int treinoId = listaTreinos.get(indiceTreino).getId();
        int exercicioId = listaExercicios.get(indiceExercicio).getId();

        boolean retorno;

        if (treinoIdEditando == 0 && exercicioIdEditando == 0) {

            TreinoExercicio item = new TreinoExercicio(treinoId, exercicioId, series, repeticoes, carga);

            retorno = TreinoExerciciosController.salvar(item);

            if (retorno) {
                Mensagem.informacao("Exercício associado ao treino com sucesso!");
            } else {
                Mensagem.erro(
                        "Erro ao associar exercício. "
                        + "Verifique se ele já está vinculado a esse treino."
                );
                return;
            }

        } else {

            if (treinoId != treinoIdEditando
                    || exercicioId != exercicioIdEditando) {
                Mensagem.erro(
                        "Durante a edição, não altere o treino ou o exercício associado."
                );
                return;
            }

            TreinoExercicio item = new TreinoExercicio(
                    treinoIdEditando,
                    exercicioIdEditando,
                    series,
                    repeticoes,
                    carga
            );

            retorno = TreinoExerciciosController.editar(item);

            if (retorno) {
                Mensagem.informacao("Associação editada com sucesso!");
            } else {
                Mensagem.erro("Erro ao editar a associação.");
                return;
            }
        }

        treinoIdEditando = 0;
        exercicioIdEditando = 0;

        txtSeries.setText("");
        txtRepeticoes.setText("");
        txtCarga.setText("");

        carregaInformacoes();
    }//GEN-LAST:event_btnSalvarActionPerformed

