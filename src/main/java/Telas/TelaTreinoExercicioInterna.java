    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        System.out.println("Botão Editar clicado!");
        int linha = tblTreinoExercicio.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um exercício para editar.");
            return;
        }

        int indiceTreino = cbxTreino.getSelectedIndex();

        if (indiceTreino < 0 || indiceTreino >= listaTreinos.size()) {
            Mensagem.erro("Selecione um treino.");
            return;
        }

        int treinoId = listaTreinos.get(indiceTreino).getId();

        int exercicioId = Integer.parseInt(String.valueOf(tblTreinoExercicio.getModel().getValueAt(linha, 0)));

        TreinoExercicio item = TreinoExerciciosController.recuperaUm(treinoId, exercicioId);

        if (item == null) {
            Mensagem.erro("Associação entre treino e exercício não encontrada.");
            return;
        }

        treinoIdEditando = item.getTreinoId();
        exercicioIdEditando = item.getExercicioId();

        txtSeries.setText(String.valueOf(item.getSeries()));
        txtRepeticoes.setText(String.valueOf(item.getRepeticoes()));
        txtCarga.setText(String.valueOf(item.getCarga()));

        ArrayList<Exercicio> listaExercicios = ExerciciosController.recuperaTodos();

        for (int i = 0; i < listaExercicios.size(); i++) {
            if (listaExercicios.get(i).getId() == item.getExercicioId()) {
                cbxExercicio.setSelectedIndex(i);
                break;
            }
        }

        cbxTreino.setSelectedIndex(indiceTreino);
        jtpExercicio.setSelectedIndex(1);

    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblTreinoExercicio.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um exercício para excluir.");
            return;
        }

        int indiceTreino = cbxTreino.getSelectedIndex();

        if (indiceTreino < 0 || indiceTreino >= listaTreinos.size()) {
            Mensagem.erro("Selecione um treino.");
            return;
        }

        int treinoId = listaTreinos.get(indiceTreino).getId();

        int exercicioId = Integer.parseInt(String.valueOf(tblTreinoExercicio.getModel().getValueAt(linha, 0)));

        TreinoExercicio item = TreinoExerciciosController.recuperaUm(treinoId, exercicioId);

        if (item == null) {
            Mensagem.erro("Associação entre treino e exercício não encontrada.");
            return;
        }

        boolean retorno = TreinoExerciciosController.excluir(item.getTreinoId(), item.getExercicioId());

        if (retorno) {
            Mensagem.informacao("Exercício removido do treino com sucesso!");

            treinoIdEditando = 0;
            exercicioIdEditando = 0;

            txtSeries.setText("");
            txtRepeticoes.setText("");
            txtCarga.setText("");

            carregaInformacoes();
        } else {
            Mensagem.erro("Não foi possível remover o exercício do treino.");
        }


    }//GEN-LAST:event_btnExcluirActionPerformed

