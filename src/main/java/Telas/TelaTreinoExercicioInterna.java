    private void carregarCombos() {

        cbxTreino.removeAllItems();

        listaTreinos = TreinosController.recuperaTodos();

        for (Treino treino : listaTreinos) {
            cbxTreino.addItem(treino.getNome());
        }

        cbxExercicio.removeAllItems();

        ArrayList<Exercicio> listaExercicios = ExerciciosController.recuperaTodos();

        for (Exercicio exercicio : listaExercicios) {
            cbxExercicio.addItem(exercicio.getNome());
        }
    }

    private void carregaInformacoes() {
        int indiceTreino = cbxTreino.getSelectedIndex();

        if (indiceTreino < 0 || indiceTreino >= listaTreinos.size()) {
            tblTreinoExercicio.setModel(new javax.swing.table.DefaultTableModel(
                    new Object[][]{},
                    new String[]{"ID Exercício", "Séries", "Repetições", "Carga"}
            ));
            return;
        }

        int idTreino = listaTreinos.get(indiceTreino).getId();

        ArrayList<TreinoExercicio> itens
                = TreinoExerciciosController.recuperaTodos(idTreino);

        tblTreinoExercicio.setModel(new AbstractTableModel() {
            @Override
            public String getColumnName(int column) {
                switch (column) {
                    case 0:
                        return "ID Exercício";
                    case 1:
                        return "Séries";
                    case 2:
                        return "Repetições";
                    case 3:
                        return "Carga";
                    default:
                        return "";
                }
            }

            @Override
            public int getColumnCount() {
                return 4;
            }

            @Override
            public int getRowCount() {
                return itens.size();
            }

            @Override
            public Object getValueAt(int rowIndex, int columnIndex) {
                TreinoExercicio item = itens.get(rowIndex);

                switch (columnIndex) {
                    case 0:
                        return item.getExercicioId();
                    case 1:
                        return item.getSeries();
                    case 2:
                        return item.getRepeticoes();
                    case 3:
                        return item.getCarga();
                    default:
                        return "";
                }
            }
        });
    }


