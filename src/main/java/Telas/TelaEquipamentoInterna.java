    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed

        String nome = txtNome.getText();
        String tipo = txtTipo.getText();
        String marca = txtMarca.getText();
        String statusAtual = txtStatus.getText();

        int quantidade;

        try {
            quantidade = Integer.parseInt(txtQuantidade.getText().trim());

            if (quantidade < 0) {
                Mensagem.erro("A quantidade não pode ser negativa.");
                return;
            }

        } catch (NumberFormatException ex) {
            Mensagem.erro("Informe uma quantidade válida.");
            return;
        }

        if (idEquipamentoEditando == 0) {

            Equipamento novoEquipamento = new Equipamento(nome, tipo, marca, quantidade, statusAtual);

            boolean retorno = EquipamentosController.salvar(novoEquipamento);

            if (retorno) {
                Mensagem.informacao("Equipamento cadastrado com sucesso!");
                txtNome.setText("");
                txtTipo.setText("");
                txtMarca.setText("");
                txtQuantidade.setText("");
                txtStatus.setText("");
                carregaInformacoes();

            } else {
                Mensagem.erro("Ocorreu um erro ao cadastrar o equipamento.");
            }

        } else {

            Equipamento editarEquipamento = new Equipamento(idEquipamentoEditando, nome, tipo, marca, quantidade, statusAtual);

            boolean retorno = EquipamentosController.editar(editarEquipamento);

            if (retorno) {
                Mensagem.informacao("Equipamento " + idEquipamentoEditando + " editado com sucesso!");

                txtNome.setText("");
                txtTipo.setText("");
                txtMarca.setText("");
                txtQuantidade.setText("");
                txtStatus.setText("");

                idEquipamentoEditando = 0;
                carregaInformacoes();

            } else {
                Mensagem.erro("Ocorreu um erro ao editar o equipamento.");
            }
        }

    }//GEN-LAST:event_btnSalvarActionPerformed


