    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        int linha = tblEquipamento.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um equipamento para editar.");
            return;
        }

        int Id = Integer.parseInt(
                String.valueOf(tblEquipamento.getModel().getValueAt(linha, 0))
        );

        Equipamento equipamento = EquipamentosController.recuperaUm(Id);

        if (equipamento == null) {
            Mensagem.erro("Equipamento não encontrado.");
        } else {
            idEquipamentoEditando = equipamento.getId();

            txtNome.setText(equipamento.getNome());
            txtTipo.setText(equipamento.getTipo());
            txtMarca.setText(equipamento.getMarca());
            txtQuantidade.setText(String.valueOf(equipamento.getQuantidade()));
            txtStatus.setText(equipamento.getStatusAtual());

            jtpAluno.setSelectedIndex(1);
            txtNome.requestFocus();
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        int linha = tblEquipamento.getSelectedRow();

        if (linha == -1) {
            Mensagem.erro("Selecione um equipamento para excluir.");
            return;
        }

        int Id = Integer.parseInt(String.valueOf(tblEquipamento.getModel().getValueAt(linha, 0)));

        Equipamento equipamento = EquipamentosController.recuperaUm(Id);

        if (equipamento == null) {
            Mensagem.erro("Equipamento não encontrado.");
        } else {
            boolean retorno = EquipamentosController.excluir(equipamento.getId());

            if (retorno) {
                Mensagem.informacao("Equipamento " + Id + " apagado com sucesso!");
                carregaInformacoes();

            } else {
                Mensagem.erro("Ocorreu um erro ao tentar excluir o equipamento " + Id);
            }
        }


    }//GEN-LAST:event_btnExcluirActionPerformed

