    private void carregaInformacoes() {
        ArrayList<Equipamento> equipamentos = EquipamentosController.recuperaTodos();

        tblEquipamento.setModel(new AbstractTableModel() {

            @Override
            public String getColumnName(int column) {
                switch (column) {
                    case 0:
                        return "ID";
                    case 1:
                        return "Nome";
                    case 2:
                        return "Tipo";
                    case 3:
                        return "Marca";
                    case 4:
                        return "Quantidade";
                    case 5:
                        return "Status atual";
                    default:
                        return "";
                }
            }

            @Override
            public int getColumnCount() {
                return 6;
            }

            @Override
            public int getRowCount() {
                return equipamentos.size();
            }

            @Override
            public Object getValueAt(int rowIndex, int columnIndex) {
                Equipamento e = equipamentos.get(rowIndex);

                switch (columnIndex) {
                    case 0:
                        return e.getId();
                    case 1:
                        return e.getNome();
                    case 2:
                        return e.getTipo();
                    case 3:
                        return e.getMarca();
                    case 4:
                        return e.getQuantidade();
                    case 5:
                        return e.getStatusAtual();
                    default:
                        return "";
                }
            }
        });
    }


